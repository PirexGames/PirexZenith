using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Reflection;
using System.Text;
using PirexZenith;
using UnityEditor;
using UnityEngine;

namespace PirexZenith.Editor
{
    /// <summary>
    /// Scans project assemblies and generates static C# factory code for AOT / IL2CPP zero-reflection DI.
    /// </summary>
    public static class PirexZenithAOTBaker
    {
        private const string GeneratedFilePath = "Assets/Pirex/Zenith/Generated/PirexZenithAOTGenerated.cs";

        [MenuItem("Tools/UnityPrime/PirexZenith/Bake AOT Code Generator")]
        public static void BakeAOTCode()
        {
            Debug.Log("[PirexZenith AOT Baker] Starting AOT Code Generation scan...");
            var typesToBake = FindTypesToBake();

            var sb = new StringBuilder();
            sb.AppendLine("// FILE AUTO-GENERATED BY PIREXZENITH AOT BAKER - DO NOT MODIFY BY HAND");
            sb.AppendLine("// Generates compiled C# static constructors for Zero-Reflection & IL2CPP AOT safety.");
            sb.AppendLine("using System;");
            sb.AppendLine("using PirexZenith;");
            sb.AppendLine();
            sb.AppendLine("namespace PirexZenith.Generated");
            sb.AppendLine("{");
            sb.AppendLine("    public static class PirexZenithAOTGenerated");
            sb.AppendLine("    {");
            sb.AppendLine("        [UnityEngine.RuntimeInitializeOnLoadMethod(UnityEngine.RuntimeInitializeLoadType.SubsystemRegistration)]");
            sb.AppendLine("        public static void RegisterAll()");
            sb.AppendLine("        {");
            sb.AppendLine("            PirexZenithAOTCache.Clear();");
            sb.AppendLine();

            int bakedCount = 0;
            foreach (var type in typesToBake)
            {
                var codeLine = GenerateRegistrationLine(type);
                if (!string.IsNullOrEmpty(codeLine))
                {
                    sb.AppendLine($"            {codeLine}");
                    bakedCount++;
                }
            }

            sb.AppendLine("        }");
            sb.AppendLine("    }");
            sb.AppendLine("}");

            var directory = Path.GetDirectoryName(GeneratedFilePath);
            if (!Directory.Exists(directory))
            {
                Directory.CreateDirectory(directory);
            }

            File.WriteAllText(GeneratedFilePath, sb.ToString(), Encoding.UTF8);
            AssetDatabase.Refresh();

            Debug.Log($"[PirexZenith AOT Baker] Successfully baked {bakedCount} static AOT resolver(s) to '{GeneratedFilePath}'.");
        }

        private static List<Type> FindTypesToBake()
        {
            var result = new List<Type>();
            var assemblies = AppDomain.CurrentDomain.GetAssemblies();

            foreach (var asm in assemblies)
            {
                var name = asm.GetName().Name;
                if (name.StartsWith("UnityEngine", StringComparison.OrdinalIgnoreCase) ||
                    name.StartsWith("UnityEditor", StringComparison.OrdinalIgnoreCase) ||
                    name.Contains("Editor") || // Bỏ qua tất cả các Assembly chứa chữ Editor (VD: Assembly-CSharp-Editor)
                    name.StartsWith("System", StringComparison.OrdinalIgnoreCase) ||
                    name.StartsWith("Mono.", StringComparison.OrdinalIgnoreCase) ||
                    name.StartsWith("mscorlib", StringComparison.OrdinalIgnoreCase) ||
                    name.StartsWith("Microsoft", StringComparison.OrdinalIgnoreCase) ||
                    name.StartsWith("nunit", StringComparison.OrdinalIgnoreCase))
                {
                    continue;
                }

                Type[] types;
                try
                {
                    types = asm.GetTypes();
                }
                catch
                {
                    continue;
                }

                foreach (var type in types)
                {
                    // Skip types that are internal, private, or protected.
                    // The globally generated AOT file cannot access them if they are in other assemblies or nested.
                    if (!type.IsPublic && !type.IsNestedPublic) continue;

                    if (type.IsClass && !type.IsAbstract && !type.IsGenericTypeDefinition && !type.IsInterface &&
                        !type.Name.Contains("<") && !type.Name.Contains("$") && !type.Name.Contains("`") &&
                        !Attribute.IsDefined(type, typeof(System.Runtime.CompilerServices.CompilerGeneratedAttribute)) &&
                        !typeof(MonoBehaviour).IsAssignableFrom(type) && !typeof(ScriptableObject).IsAssignableFrom(type) &&
                        !typeof(Attribute).IsAssignableFrom(type) && !typeof(Delegate).IsAssignableFrom(type) &&
                        !typeof(Exception).IsAssignableFrom(type))
                    {
                        if (ShouldBakeType(type))
                        {
                            result.Add(type);
                        }
                    }
                }
            }

            return result;
        }

        private static bool ShouldBakeType(Type type)
        {
            if (type.Namespace != null && type.Namespace.StartsWith("PirexZenith.Editor.Benchmark", StringComparison.Ordinal))
            {
                return true;
            }

            var ctors = type.GetConstructors(BindingFlags.Public | BindingFlags.Instance | BindingFlags.DeclaredOnly);
            if (ctors.Length == 0) return false;

            foreach (var ctor in ctors)
            {
                if (Attribute.IsDefined(ctor, typeof(InjectAttribute)))
                {
                    return true;
                }
            }

            if (type.Namespace != null && (
                type.Namespace.StartsWith("PirexZenith.GameplaySample", StringComparison.Ordinal) ||
                type.Namespace.StartsWith("PirexGames", StringComparison.Ordinal)))
            {
                return true;
            }

            return false;
        }

        private static string GenerateRegistrationLine(Type type)
        {
            var ctors = type.GetConstructors(BindingFlags.Public | BindingFlags.Instance | BindingFlags.DeclaredOnly);
            if (ctors.Length == 0) return null;

            ConstructorInfo selectedCtor = null;
            foreach (var c in ctors)
            {
                if (Attribute.IsDefined(c, typeof(InjectAttribute)))
                {
                    selectedCtor = c;
                    break;
                }
            }

            if (selectedCtor == null)
            {
                selectedCtor = ctors.OrderByDescending(c => c.GetParameters().Length).First();
            }

            var parameters = selectedCtor.GetParameters();
            var fullName = GetSafeTypeName(type);

            if (parameters.Length == 0)
            {
                return $"PirexZenithAOTCache.Register<{fullName}>(res => new {fullName}());";
            }

            var args = new List<string>();
            foreach (var p in parameters)
            {
                var paramType = GetSafeTypeName(p.ParameterType);
                args.Add($"({paramType})res.Resolve(typeof({paramType}))");
            }

            string argString = string.Join(", ", args);
            return $"PirexZenithAOTCache.Register<{fullName}>(res => new {fullName}({argString}));";
        }

        private static string GetSafeTypeName(Type type)
        {
            return type.FullName?.Replace("+", ".");
        }
    }
}
